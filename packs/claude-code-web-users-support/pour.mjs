// Pouring a person's pack into the session: the mechanics, as one function two callers
// share. `session-prepare.mjs` calls it in the phase before the session's pack set is
// read, which is where it belongs; `session-start.mjs` calls it only when that phase did
// not run at all, which is what a member holding this pack beside an older engine has.
// The pack and engine lanes deliver on separate cycles, so that window is ordinary rather
// than exceptional, and what the person loses in it is the mount of their skills - never
// their rules, which the late caller injects itself.
//
// WHY A WHOLE PACK AND NOT A FILE. What a person wants a session to know is not only
// prose. It is a skill they reach for, a check that catches the mistake they keep making,
// a requirement their tooling needs installed. Every one of those already has a carrier -
// the pack - with an engine that mounts, runs and reports it. Pouring a pack gets all of
// them at once; the file this replaced could only ever carry the first.
//
// WHY THE CONTENT IS NOT HERE. It belongs to a person, not to a project and not to the
// shared canon - which every fleet mounts, and which is therefore both the wrong host for
// one group's people and the wrong authority on where they live. So this pack carries the
// ADDRESS (its entry `config`, read via store.mjs) and the group carries the content.
//
// LOCAL FIRST. When this tree IS the store, the working copy is what the owner is reading
// and editing - a fetch would serve the default branch and quietly hide the edit in
// progress.
//
// ATTENDED SESSIONS ONLY. A routine fired under a person's account carries their identity
// but not their presence, and a pack written for a present person (a popup for every
// decision, a callout closing every turn) misdirects a run nobody is watching. The harness
// says which it is in CLAUDE_CODE_SESSION_ATTENDED; only an explicit "not attended"
// declines, so an older harness that never sets it still pours.
//
// FAIL-SOFT ON EVERY MISS. No identity, no configured store, no pack, a fetch that fails:
// the pour leaves an empty pack behind and returns why, which its caller turns into the
// one note a reader sees. Nothing here is load-bearing - the packs, checks and skills a
// session needs are already local.
//
// WHAT IT WILL WRITE, and nothing else: Markdown, JavaScript modules and JSON, under one
// directory, within a file count and byte budget. A pack is executable code that will run
// inside this session's hooks, so the store repo is as trusted as the repository itself -
// stated in the pack's README, because no cap here can substitute for that.

import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync, statSync, mkdtempSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { removeTree } from '../../engine/remove-tree.mjs';
import { resolveStore, folderFor, legacyFileFor, isUsableIdentity } from './store.mjs';

const CLONE_TIMEOUT_MS = 60_000;

// The budget a person's pack is poured within. Generous for what a pack is, small enough
// that a mistake in the store cannot fill a session's disk or its context.
const MAX_FILES = 60;
const MAX_BYTES = 512 * 1024;
const POURABLE = /\.(md|mjs|json)$/;

// Where the session's pack root and this pack's directory inside it sit. The engine owns
// both names (engine/pack_loader/pack-registry.mjs); they are spelled here rather than
// imported because a member's vendored engine may predate them, and a step that fails to
// import is a step that never ran.
const PACK_DIR = join('.claudinite', 'temp', 'packs', 'current_user');
const RECEIPT = '.pour.json';

export const packDirIn = (root) => join(root, PACK_DIR);
export const receiptIn = (root) => join(packDirIn(root), RECEIPT);
export const proseIn = (root) => join(packDirIn(root), 'RULES.md');

// The manifest the poured pack runs under when the person's own directory carries none -
// the ordinary case, because a person with rules to state should not have to write a
// manifest to state them. Their own pack.mjs is poured untouched when they have one; it
// must set neither `id`, which the engine takes from the directory and this directory is
// the session's, nor `version`, which a pack distributed to nobody has nothing to hold.
const SYNTHESIZED_MANIFEST = `// GENERATED by claude-code-web-users-support: the manifest the person's own pack
// directory did not carry. Edit nothing here - it is rewritten every session.
export default {
  ruleRoutingGuidance: {
    belongs: 'how this person wants to be worked with, in every project they work in',
    excludes: 'a project\\'s own conventions - those belong to the packs that own each subject',
  },
};
`;

const PLACEHOLDER = '<!-- No personal pack was poured into this session. -->\n';

// Every file under a directory in this tree, as paths relative to it.
function treeFiles(absDir, prefix = '') {
  const out = [];
  for (const entry of readdirSync(absDir, { withFileTypes: true })) {
    if (entry.name === '.git') continue;
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...treeFiles(join(absDir, entry.name), rel));
    else if (entry.isFile()) out.push(rel);
  }
  return out;
}

// One git call, with its own clock, reporting the line git ended on.
function git(args, cwd) {
  const run = spawnSync('git', args, { cwd, encoding: 'utf8', timeout: CLONE_TIMEOUT_MS });
  if (run.error?.code === 'ETIMEDOUT') throw new Error(`git ${args[0]} did not finish in ${Math.round(CLONE_TIMEOUT_MS / 1000)}s`);
  if (run.status !== 0) throw new Error((run.stderr || `git ${args[0]} exited ${run.status}`).trim().split('\n').pop());
}

// The store's default branch with only this person's directory checked out, in a directory
// the caller removes. A CLONE and not a download: this repo's own experience is that
// codeload and the repo-scoped API are both denied by the sandbox proxy where git against
// the same repository is not, and a private store is reachable at all only through the
// credentials git is already configured with. Shallow and blob-filtered, so what it costs
// is one person's directory rather than the store's history.
function checkout(store, folder) {
  const dir = mkdtempSync(join(tmpdir(), 'claudinite-personal-pack-'));
  git(['clone', '--depth', '1', '--filter=blob:none', '--sparse',
    process.env.CLAUDINITE_PREFS_CLONE_URL || `https://github.com/${store.repo}`, dir]);
  git(['sparse-checkout', 'set', '--no-cone', folder, `${folder}.md`], dir);
  return dir;
}

// Pour the pack belonging to `env.CLAUDE_CODE_USER_EMAIL` into `root`'s session pack root,
// and return the receipt describing what happened. Always leaves the directory in a state
// the engine can load: an empty pack when there was nothing to pour.
export function pour({ root, config, env }) {
  const dest = packDirIn(root);
  let release = () => {};

  // What happened, for a caller to say. Written last and always: a session where this file
  // is absent is a session where nothing poured at all, which is a different thing from a
  // pour that found nothing.
  const finish = (receipt) => {
    release();
    try {
      mkdirSync(dest, { recursive: true });
      if (!existsSync(join(dest, 'RULES.md'))) writeFileSync(join(dest, 'RULES.md'), PLACEHOLDER);
      writeFileSync(join(dest, RECEIPT), `${JSON.stringify(receipt, null, 2)}\n`);
    } catch (e) {
      return { ...receipt, unwritable: e.message };
    }
    return receipt;
  };

  const store = resolveStore(config);
  if (!store) return finish({ outcome: 'no-store' });
  if (env.CLAUDE_CODE_SESSION_ATTENDED === '0') return finish({ outcome: 'unattended' });

  const email = env.CLAUDE_CODE_USER_EMAIL || '';
  if (!email) return finish({ outcome: 'no-identity' });
  if (!isUsableIdentity(email)) return finish({ outcome: 'unusable-identity', identity: String(email).replace(/["\\]/g, '') });

  // LOCAL FIRST, then the store. Either way what is read is a directory in a working tree,
  // so one reader covers both - and a test points the clone at a path.
  const folder = folderFor(store, email);
  const legacy = legacyFileFor(store, email);
  let src;
  try {
    let base = root;
    if (!existsSync(join(root, folder)) && !existsSync(join(root, legacy))) {
      const clone = checkout(store, folder);
      release = () => { try { removeTree(clone); } catch { /* it outlives the session at worst */ } };
      base = clone;
    }
    const where = base === root ? 'working tree' : store.repo;
    const dir = join(base, folder);
    if (existsSync(dir) && statSync(dir).isDirectory()) {
      src = { where, files: treeFiles(dir), read: (p) => readFileSync(join(dir, p)) };
    } else if (existsSync(join(base, legacy))) {
      src = { where, legacy: true, files: ['RULES.md'], read: () => readFileSync(join(base, legacy)) };
    } else {
      src = { where, files: [] };
    }
  } catch (e) {
    return finish({ outcome: 'unreadable', where: store.repo, why: e.message });
  }

  const wanted = src.files.filter((p) => POURABLE.test(p) && !p.split('/').includes('..'));
  if (!wanted.length) return finish({ outcome: src.files.length ? 'nothing-pourable' : 'no-pack', where: src.where });
  if (wanted.length > MAX_FILES) {
    return finish({ outcome: 'too-many-files', where: src.where, files: wanted.length, limit: MAX_FILES });
  }

  // Empty the directory before pouring: a pack left by an earlier session, for an earlier
  // person or an earlier version of this one's, is content nobody chose. The root is the
  // engine's session state and this pack's own subdirectory within it, so nothing tracked
  // is ever at risk.
  try {
    removeTree(dest);
    mkdirSync(dest, { recursive: true });
  } catch (e) {
    return finish({ outcome: 'unreadable', where: src.where, why: `the session pack root is unwritable: ${e.message}` });
  }

  let bytes = 0;
  let words = 0;
  const poured = [];
  for (const rel of wanted) {
    let content;
    try {
      content = src.read(rel);
    } catch (e) {
      return finish({ outcome: 'unreadable', where: src.where, why: `${rel}: ${e.message}` });
    }
    bytes += content.length;
    if (bytes > MAX_BYTES) return finish({ outcome: 'too-large', where: src.where, limit: MAX_BYTES });
    if (rel.endsWith('.md')) words += content.toString('utf8').trim().split(/\s+/).filter(Boolean).length;

    // Path-checked against the destination it claims to sit in.
    const target = join(dest, rel);
    const inside = relative(dest, target);
    if (inside.startsWith('..') || inside.startsWith(sep) || inside === '') continue;
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
    poured.push(rel);
  }

  if (!poured.includes('pack.mjs')) writeFileSync(join(dest, 'pack.mjs'), SYNTHESIZED_MANIFEST);

  return finish({ outcome: 'poured', where: src.where, legacy: Boolean(src.legacy), identity: email, files: poured, words });
}
