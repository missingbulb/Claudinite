// THE STORE'S CODEOWNERS BLOCK, derived from the directories the store holds. A person's pack is
// code that runs in their sessions, so each directory is owned by its person, and a required
// code-owner review then lets each person know that no one but them or the store's admin
// changed it. Generated, never hand-kept: the block is a pure function of the tree, so the
// check (worldRules/store-codeowners.mjs) and the writer (write_store_codeowners.mjs) compute
// the same text from the same files.
//
// THE LINES, in the order that makes GitHub's last-match-wins rule come out right:
//
//   /<path>/                  @<admin>              a new directory needs the admin's approval
//   /<path>/<login>/          @<login> @<admin>     one per person
//   /.github/CODEOWNERS       @<admin>              nobody re-owns the store by editing this file
//
// The admin sits beside each person because GitHub never counts a PR's author as a code
// owner's approval: a person editing their own pack needs someone else who owns it, and only
// the admin is trusted with that. The admin is the store repository's owning account; an
// organization-owned store, whose owner is not a user, is not supported. An email-named
// directory, the legacy form, is owned by the email, which GitHub resolves to the account it
// is added to.
//
// Pure: the caller supplies the store and the tracked file list.

import { storeDirForm } from './user_pack_address.mjs';

export const CODEOWNERS_FILE = '.github/CODEOWNERS';
export const BEGIN = '# BEGIN GENERATED by claude-code-web-users-support';
export const END = '# END GENERATED by claude-code-web-users-support';

export const adminOf = (store) => `@${store.repo.split('/')[0]}`;

// The store's top-level person directories, sorted, each with the owner token GitHub reads.
export function personDirs(store, files) {
  const prefix = `${store.path}/`;
  const names = new Set();
  for (const f of files) {
    if (!f.startsWith(prefix)) continue;
    const rest = f.slice(prefix.length);
    if (rest.includes('/')) names.add(rest.slice(0, rest.indexOf('/')));
  }
  return [...names].sort().flatMap((name) => {
    const form = storeDirForm(name);
    if (form === 'login') return [{ name, owner: `@${name}` }];
    if (form === 'email') return [{ name, owner: name }];
    return []; // unaddressable - preferences-store-file-names names it, and the admin line covers it
  });
}

export function codeownersBlock(store, files) {
  const admin = adminOf(store);
  return [
    BEGIN,
    `# from ${store.path}/ - regenerate with write_store_codeowners.mjs, never edit by hand`,
    `/${store.path}/ ${admin}`,
    ...personDirs(store, files).map(({ name, owner }) => `/${store.path}/${name}/ ${owner} ${admin}`),
    `/${CODEOWNERS_FILE} ${admin}`,
    END,
  ].join('\n');
}

// `existing` with the block in place: replaced where it stands, else appended. Everything
// outside the markers is the store's own and kept byte for byte.
export function withBlock(existing, block) {
  const text = existing ?? '';
  const start = text.indexOf(BEGIN);
  const end = start === -1 ? -1 : text.indexOf(END, start);
  if (start !== -1 && end !== -1) return `${text.slice(0, start)}${block}${text.slice(end + END.length)}`;
  const sep = text === '' || text.endsWith('\n') ? '' : '\n';
  return `${text}${sep}${block}\n`;
}

// The generated block as it stands in `text`, or null; and whether an owner line follows it.
export function readBlock(text) {
  const start = text.indexOf(BEGIN);
  const end = start === -1 ? -1 : text.indexOf(END, start);
  if (start === -1 || end === -1) return null;
  const after = text.slice(end + END.length).split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  return { block: text.slice(start, end + END.length), ownerLinesAfter: after };
}
